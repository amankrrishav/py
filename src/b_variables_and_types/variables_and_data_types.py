# Variables and Dynamic Typing in Python

name = "aman"        # string (str)
age = 20             # integer (int)
gpa = 7.9            # floating point (float)
is_student = True    # boolean (bool)

print("Name:", name, "| GPA:", gpa)
print("Type of is_student:", type(is_student))

# f-string formatting
print(f"{name} is {age} years old with GPA {gpa}")
