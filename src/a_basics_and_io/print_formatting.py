# Print Formatting & Parameters in Python

# Multiple values printed with default space separator
print("aman", 'aman', 21)

# Quotes within quotes
print('one " string', 'aman and \'rishav')

# sep parameter: customize delimiter between arguments
print("xyz", "xyz", 'xyz', sep=", ")

# end parameter: customize trailing character (default is newline)
print("Hello", end=" // ")
print("World")
