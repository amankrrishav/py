# User Input in Python

# input() always returns a string (str)
n = input("Enter any number: ")
print("You entered:", n)
print("Type of input:", type(n))
print("String multiplication (n * 3):", n * 3)
print("String concatenation (n + n):", n + n)

# Convert string input to integer
num = int(input("Enter the same number again: "))
print("Numeric multiplication (num * 3):", num * 3)
print("Numeric addition (num + num):", num + num)
