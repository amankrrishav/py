# Arithmetic Operators in Python

a = 20
b = 2

print("Addition (a + b):", a + b)           # 22
print("Subtraction (a - b):", a - b)        # 18
print("Multiplication (a * b):", a * b)     # 40
print("True Division (a / b):", a / b)      # 10.0 (returns float)
print("Floor Division (a // b):", a // b)   # 10 (integer division)
print("Modulus (a % b):", a % b)            # 0 (remainder)
print("Exponentiation (a ** b):", a ** b)   # 400 (power)
